#!/usr/bin/env bash
# Build smprobe for Linux x86_64.
#
#   ./build.sh            compile smprobe.c with the checked-in kernels.h (needs gcc only)
#   ./build.sh kernels    regenerate kernels.h from smprobe.ptx first (needs ptxas)
#
# ptxas comes with the CUDA toolkit, or without it from the PyPI wheel
# nvidia-cuda-nvcc-cu12 (unzip it and point PTXAS at nvidia/cuda_nvcc/bin/ptxas).
#
# Build on an old distribution (for example ubuntu:20.04) so that the binary
# runs on any newer glibc. libgcc is linked statically; the only run-time
# dependencies are glibc and libcuda.so.1, which is opened with dlopen().
set -euo pipefail
cd "$(dirname "$0")"

# One cubin per GPU generation; a cubin runs on every later minor version of
# the same major version (sm_70 on a T4, which is 7.5).
# Each entry is <sm>:<lowest PTX version that knows it>.
ARCHS=${ARCHS:-"50:6.4 60:6.4 70:6.4 80:7.0 90:7.8 100:8.6 120:8.7"}
PTXAS=${PTXAS:-ptxas}
CC=${CC:-gcc}

gen_kernels() {
  local tmp
  tmp=$(mktemp -d)
  {
    echo "/* Generated by build.sh from smprobe.ptx with $("$PTXAS" --version | head -1). Do not edit. */"
    echo "#ifndef SMPROBE_KERNELS_H"
    echo "#define SMPROBE_KERNELS_H"
    echo "struct smprobe_cubin { int major, minor; const char *name; const unsigned char *data; unsigned int size; };"
    echo "static const char smprobe_ptx[] ="
    grep -v '^//' smprobe.ptx | sed -e '/^[[:space:]]*$/d' -e 's/[[:space:]]*\/\/.*$//' -e 's/\\/\\\\/g' -e 's/"/\\"/g' -e 's/^/  "/' -e 's/$/\\n"/'
    echo "  ;"
  } >"$tmp/kernels.h"

  local table=""
  for entry in $ARCHS; do
    local a=${entry%%:*} v=${entry##*:}
    sed -e "s/^\.version .*/.version $v/" -e "s/^\.target .*/.target sm_$a/" smprobe.ptx >"$tmp/k_$a.ptx"
    if ! "$PTXAS" --gpu-name "sm_$a" -O3 -o "$tmp/k_$a.cubin" "$tmp/k_$a.ptx" 2>"$tmp/err"; then
      echo "skip sm_$a: $(head -1 "$tmp/err")" >&2
      continue
    fi
    {
      echo "static const unsigned char smprobe_cubin_sm_$a[] __attribute__((aligned(16))) = {"
      od -An -v -tx1 "$tmp/k_$a.cubin" | sed -e 's/ \([0-9a-f][0-9a-f]\)/0x\1,/g' -e 's/^/  /'
      echo "};"
    } >>"$tmp/kernels.h"
    table+="  {$((a / 10)), $((a % 10)), \"cubin sm_$a\", smprobe_cubin_sm_$a, sizeof(smprobe_cubin_sm_$a)},"$'\n'
  done
  {
    echo "static const struct smprobe_cubin smprobe_cubins[] = {"
    printf '%s' "$table"
    echo "};"
    echo "static const unsigned int smprobe_cubin_count = sizeof(smprobe_cubins) / sizeof(smprobe_cubins[0]);"
    echo "#endif"
  } >>"$tmp/kernels.h"
  mv "$tmp/kernels.h" kernels.h
  rm -rf "$tmp"
}

if [ "${1:-}" = "kernels" ]; then
  gen_kernels
fi

"$CC" -O2 -Wall -Wextra -std=gnu11 -static-libgcc -o smprobe smprobe.c -ldl
strip smprobe
sha256sum smprobe >smprobe.sha256
ls -l smprobe
cat smprobe.sha256
